import { readFile, writeFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';
const root = new URL('./', import.meta.url);
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
const model = (await readFile(new URL('src/model.mjs', root), 'utf8')).replaceAll('export function ', 'function ');
const ui = (await readFile(new URL('src/ui.mjs', root), 'utf8'))
  .replace("import { deriveTaskRows, sameRows, currentSessionId, directoryLabel, createPopupState, createOutcomeLoader } from './model.mjs';\n", '')
  .replace('export function createClientPlugin', 'function createClientPlugin');
const client = `// Generated by build.mjs. Edit src/*.mjs, then rebuild.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(manifest.name)},\n  factory(require) {\n${model}\n${ui}\n    return createClientPlugin(require('react'));\n  },\n});\n`;
// Parse only: no mock React, browser, DOM, app shell, or private runtime is executed.
new Script(client, { filename: 'client.js' });
await writeFile(new URL('client.js', root), client, 'utf8');
for (const name of ['index.js', 'client.js', 'src/outcome.mjs', 'cordis.patch.yml', 'icon.svg', 'locale/en.json', 'locale/zh.json']) {
  await access(new URL(name, root));
}
if (manifest.exports['./client'] !== './client.js' || manifest.dsh.bundle.patch !== './cordis.patch.yml') {
  throw new Error('Invalid bundle exports or patch.');
}
for (const locale of ['en', 'zh']) {
  const value = JSON.parse(await readFile(new URL(`locale/${locale}.json`, root), 'utf8'));
  if (!value.meta?.title || !value.meta?.description) throw new Error(`Missing ${locale} display metadata.`);
}
const icon = await readFile(new URL('icon.svg', root), 'utf8');
if (Buffer.byteLength(icon) > 256 * 1024 || !icon.includes('xmlns="http://www.w3.org/2000/svg"')) throw new Error('Invalid icon.');
if (/require\(['"]@deepseek-ai\/dsh-client-/.test(client)) throw new Error('Private UI-module import.');
console.log(`Built and validated ${manifest.name}@${manifest.version}: ${fileURLToPath(new URL('client.js', root))}`);
